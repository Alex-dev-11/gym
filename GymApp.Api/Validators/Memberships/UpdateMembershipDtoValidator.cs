using FluentValidation;
using GymApp.Api.DTOs.Memberships;

namespace GymApp.Api.Validators;

/// <summary>
/// Валидатор для UpdateMembershipDto.
/// Проверяет, что данные для обновления абонемента корректны.
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЖНО: ВАЛИДАТОР НЕ ИМЕЕТ ДОСТУПА К БД!
/// ═══════════════════════════════════════════════════════════════
/// 
/// Валидатор проверяет ТОЛЬКО формат и допустимые значения полей.
/// Он НЕ может делать запросы к БД для проверки:
/// - Существования абонемента (ID из URL)
/// - Текущего статуса абонемента (нельзя менять completed/expired)
/// - Соответствия EndDate >= StartDate абонемента
/// 
/// Эти проверки делаются в MembershipService (бизнес-логика).
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ:
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ Status (если передан) ∈ {'active', 'cancelled'}
/// ✅ EndDate (если передана) не в прошлом
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО НЕ ПРОВЕРЯЕТСЯ ЗДЕСЬ (делается в сервисе):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ❌ Существование абонемента (ID из URL)
///    → Валидатор не имеет доступа к БД
///    → Проверяется в MembershipService через _context.Memberships.FindAsync()
/// 
/// ❌ EndDate >= StartDate абонемента
///    → Валидатор не знает StartDate конкретного абонемента
///    → Проверяется в MembershipService после загрузки абонемента из БД
/// 
/// ❌ Статус абонемента (нельзя менять completed/expired)
///    → Это бизнес-логика, требует запроса к БД
///    → Проверяется в MembershipService
/// </summary>
public class UpdateMembershipDtoValidator : AbstractValidator<UpdateMembershipDto>
{
    public UpdateMembershipDtoValidator()
    {
        // ═══════════════════════════════════════════════════════════════
        // Правило 1: Status (если передан) должен быть 'active' или 'cancelled'
        // ═══════════════════════════════════════════════════════════════
        // Разрешаем null (не менять статус) И допустимые значения.
        // Статусы 'completed' и 'expired' устанавливаются АВТОМАТИЧЕСКИ,
        // админ не должен их менять вручную.
        RuleFor(x => x.Status)
            .Must(status => status == null || status == "active" || status == "cancelled")
            .WithMessage("Статус может быть только 'active' или 'cancelled'. " +
                        "Статусы 'completed' и 'expired' устанавливаются автоматически.");

        // ═══════════════════════════════════════════════════════════════
        // Правило 2: EndDate (если передана) не должна быть в прошлом
        // ═══════════════════════════════════════════════════════════════
        // Разрешаем null (не менять дату) И допустимые значения.
        // Проверка "EndDate >= StartDate абонемента" делается в сервисе,
        // потому что валидатор не знает StartDate конкретного абонемента.
        RuleFor(x => x.EndDate)
            .Must(endDate => endDate == null || endDate.Value.Date >= DateTime.Today)
            .WithMessage("Дата окончания не может быть в прошлом");
    }
}