using FluentValidation;
using GymApp.Api.DTOs.Memberships;

namespace GymApp.Api.Validators;

/// <summary>
/// Валидатор для CreateMembershipDto.
/// Проверяет, что данные для создания абонемента корректны.
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЖНО: ВАЛИДАТОР НЕ ИМЕЕТ ДОСТУПА К БД!
/// ═══════════════════════════════════════════════════════════════
/// 
/// Валидатор проверяет ТОЛЬКО формат и допустимые значения полей.
/// Он НЕ может делать запросы к БД для проверки:
/// - Существования клиента (ClientId ссылается на реального клиента)
/// - Наличия активного абонемента у клиента
/// 
/// Эти проверки делаются в MembershipService (бизнес-логика).
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ:
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ ClientId > 0 (базовая проверка, что ID положительный)
/// ✅ Type не пустой и ∈ {'single', 'month', 'year'}
/// ✅ StartDate не в прошлом (или сегодня)
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО НЕ ПРОВЕРЯЕТСЯ ЗДЕСЬ (делается в сервисе):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ❌ Существование клиента (ClientId ссылается на реального клиента)
///    → Валидатор не имеет доступа к БД
///    → Проверяется в MembershipService через _context.Clients.FindAsync()
/// 
/// ❌ Наличие активного абонемента у клиента (для автозакрытия)
///    → Это бизнес-логика, требует запроса к БД
///    → Проверяется в MembershipService через _context.Memberships.AnyAsync()
/// </summary>
public class CreateMembershipDtoValidator : AbstractValidator<CreateMembershipDto>
{
    public CreateMembershipDtoValidator()
    {
        // ═══════════════════════════════════════════════════════════════
        // Правило 1: ClientId должен быть > 0
        // ═══════════════════════════════════════════════════════════════
        // Базовая проверка, что ID положительный.
        // Проверка существования клиента (ссылается ли на реального клиента)
        // делается в сервисе, потому что валидатор не имеет доступа к БД.
        RuleFor(x => x.ClientId)
            .GreaterThan(0)
            .WithMessage("ID клиента должен быть больше 0");

        // ═══════════════════════════════════════════════════════════════
        // Правило 2: Type не должен быть пустым
        // ═══════════════════════════════════════════════════════════════
        // Проверяем, что поле заполнено.
        RuleFor(x => x.Type)
            .NotEmpty()
            .WithMessage("Тип абонемента обязателен для заполнения")

            // ═══════════════════════════════════════════════════════════════
            // Правило 3: Type должен быть одним из допустимых значений
            // ═══════════════════════════════════════════════════════════════
            // Проверяем, что тип ∈ {'single', 'month', 'year'}.
            // Это соответствует CHECK constraint в БД.
            .Must(type => type == "single" || type == "month" || type == "year")
            .WithMessage("Тип абонемента должен быть 'single', 'month' или 'year'");

        // ═══════════════════════════════════════════════════════════════
        // Правило 4: StartDate не должен быть в прошлом
        // ═══════════════════════════════════════════════════════════════
        // Проверяем, что дата начала >= сегодня.
        // Нельзя создать абонемент с датой начала вчера.
        RuleFor(x => x.StartDate)
            .GreaterThanOrEqualTo(DateTime.Today)
            .WithMessage("Дата начала не может быть в прошлом");
    }
}