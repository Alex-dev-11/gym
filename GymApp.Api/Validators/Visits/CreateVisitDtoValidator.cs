using FluentValidation;
using GymApp.Api.DTOs.Visits;

namespace GymApp.Api.Validators.Visits;

/// <summary>
/// Валидатор для CreateVisitDto.
/// Проверяет, что данные для регистрации посещения корректны.
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЖНО: ВАЛИДАТОР НЕ ИМЕЕТ ДОСТУПА К БД!
/// ═══════════════════════════════════════════════════════════════
/// 
/// Валидатор проверяет ТОЛЬКО формат и допустимые значения полей.
/// Он НЕ может делать запросы к БД для проверки:
/// - Существования абонемента (MembershipId ссылается на реальный абонемент)
/// - Статуса абонемента (должен быть 'active')
/// - Лимита посещений (used_visits < total_visits)
/// 
/// Эти проверки делаются в VisitService (бизнес-логика).
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ:
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ MembershipId > 0 (базовая проверка, что ID положительный)
/// ✅ TrainerId (если передан) > 0
/// ✅ ProcessedByUserId (если передан) > 0
/// 
/// ═══════════════════════════════════════════════════════════════
/// ЧТО НЕ ПРОВЕРЯЕТСЯ ЗДЕСЬ (делается в сервисе):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ❌ Существование абонемента (MembershipId ссылается на реальный абонемент)
///    → Валидатор не имеет доступа к БД
///    → Проверяется в VisitService через _context.Memberships.FindAsync()
/// 
/// ❌ Статус абонемента (должен быть 'active')
///    → Это бизнес-логика, требует запроса к БД
///    → Проверяется в VisitService
/// 
/// ❌ Лимит посещений (used_visits < total_visits)
///    → Это бизнес-логика, требует запроса к БД
///    → Проверяется в VisitService
/// </summary>
public class CreateVisitDtoValidator : AbstractValidator<CreateVisitDto>
{
    public CreateVisitDtoValidator()
    {
        // ═══════════════════════════════════════════════════════════════
        // Правило 1: MembershipId должен быть > 0
        // ═══════════════════════════════════════════════════════════════
        // Базовая проверка, что ID положительный.
        // Проверка существования абонемента (ссылается ли на реальный абонемент)
        // делается в сервисе, потому что валидатор не имеет доступа к БД.
        RuleFor(x => x.MembershipId)
            .GreaterThan(0)
            .WithMessage("ID абонемента должен быть больше 0");

        // ═══════════════════════════════════════════════════════════════
        // Правило 2: TrainerId (если передан) должен быть > 0
        // ═══════════════════════════════════════════════════════════════
        // Разрешаем null (клиент занимался самостоятельно) И положительные значения.
        RuleFor(x => x.TrainerId)
            .Must(trainerId => trainerId == null || trainerId > 0)
            .WithMessage("ID тренера должен быть больше 0");

        // ═══════════════════════════════════════════════════════════════
        // Правило 3: ProcessedByUserId (если передан) должен быть > 0
        // ═══════════════════════════════════════════════════════════════
        // Разрешаем null (посещение зарегистрировано через терминал) И положительные значения.
        RuleFor(x => x.ProcessedByUserId)
            .Must(userId => userId == null || userId > 0)
            .WithMessage("ID оператора должен быть больше 0");
    }
}