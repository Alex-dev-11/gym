namespace GymApp.Api.DTOs.Memberships;

/// <summary>
/// DTO для создания нового абонемента.
/// Используется в POST /api/memberships
/// 
/// ═══════════════════════════════════════════════════════════════
/// БИЗНЕС-ЛОГИКА СОЗДАНИЯ АБОНЕМЕНТА:
/// ═══════════════════════════════════════════════════════════════
/// 
/// 1. Клиент передаёт только ClientId, Type и StartDate.
///    Остальные поля (EndDate, TotalVisits, Status, UsedVisits) 
///    рассчитываются АВТОМАТИЧЕСКИ в MembershipService.
/// 
/// 2. Автоматический расчёт EndDate и TotalVisits:
///    - single: total_visits=1, end_date=start_date+30 дней
///    - month:  total_visits=0, end_date=start_date+30 дней
///    - year:   total_visits=0, end_date=start_date+365 дней
/// 
/// 3. Автоматическое закрытие старого абонемента:
///    Если у клиента уже есть активный абонемент, он автоматически 
///    закрывается со статусом 'completed' (ценность переходит в новый).
/// 
/// 4. Начальный статус всегда 'active', UsedVisits всегда 0.
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЛИДАЦИЯ (FluentValidation):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ ПРОВЕРЯЕТСЯ в CreateMembershipDtoValidator:
///    - ClientId > 0
///    - Type не пустой и ∈ {'single', 'month', 'year'}
///    - StartDate не в прошлом (или сегодня)
/// 
/// ❌ НЕ ПРОВЕРЯЕТСЯ в валидаторе (проверяется в сервисе):
///    - Существование клиента (ClientId ссылается на реального клиента)
///      → Валидатор не имеет доступа к БД
///    - Наличие активного абонемента у клиента (для автозакрытия)
///      → Это бизнес-логика, требует запроса к БД
/// </summary>
public class CreateMembershipDto
{
    /// <summary>
    /// ID клиента, которому выдаём абонемент.
    /// Обязательное поле, должно ссылаться на существующего клиента.
    /// 
    /// Проверка существования клиента происходит в MembershipService,
    /// а не в валидаторе, потому что валидатор не имеет доступа к БД.
    /// </summary>
    public int ClientId { get; set; }

    /// <summary>
    /// Тип абонемента: 'single', 'month', 'year'.
    /// Обязательное поле, валидируется через FluentValidation.
    /// 
    /// В зависимости от типа автоматически рассчитываются:
    /// - EndDate (дата окончания)
    /// - TotalVisits (лимит посещений)
    /// 
    /// Допустимые значения проверяются в CreateMembershipDtoValidator.
    /// </summary>
    public string Type { get; set; } = string.Empty;

    /// <summary>
    /// Дата начала действия абонемента.
    /// Обязательное поле. Не может быть в прошлом.
    /// 
    /// Проверка "не в прошлом" происходит в CreateMembershipDtoValidator.
    /// </summary>
    public DateTime StartDate { get; set; }
}