namespace GymApp.Api.DTOs.Memberships;

/// <summary>
/// DTO для ответа API.
/// Содержит все данные абонемента + имя клиента (для удобства фронта).
/// 
/// ═══════════════════════════════════════════════════════════════
/// БИЗНЕС-ЛОГИКА СТАТУСОВ:
/// ═══════════════════════════════════════════════════════════════
/// 
/// - active:    Абонемент действует. Клиент может посещать зал.
/// 
/// - completed: Абонемент использован полностью ИЛИ закрыт при продлении.
///              Устанавливается АВТОМАТИЧЕСКИ:
///              - При достижении лимита посещений (used_visits == total_visits)
///              - При создании нового абонемента (старый закрывается)
/// 
/// - expired:   Абонемент истёк по времени (прошла end_date).
///              Устанавливается АВТОМАТИЧЕСКИ при регистрации посещения,
///              если дата прошла. При GET запросах статус НЕ обновляется.
/// 
/// - cancelled: Абонемент отменён вручную админом.
///              Используется ТОЛЬКО для ЧП:
///              - Возврат денег
///              - Нарушение правил зала
///              - Ошибка при создании
/// 
/// ═══════════════════════════════════════════════════════════════
/// ОПТИМИЗАЦИЯ (избегаем N+1 запросов):
/// ═══════════════════════════════════════════════════════════════
/// 
/// Поле ClientFullName заполняется через JOIN с таблицей clients
/// прямо в SQL-запросе (через EF Core .Select()).
/// Это позволяет получить имя клиента без дополнительных запросов к БД.
/// </summary>
public class MembershipResponseDto
{
    /// <summary>
    /// ID абонемента.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// ID клиента, которому принадлежит абонемент.
    /// </summary>
    public int ClientId { get; set; }

    /// <summary>
    /// Полное имя клиента (Фамилия Имя Отчество).
    /// Заполняется через JOIN с таблицей clients в MembershipService.
    /// 
    /// Это нужно, чтобы фронтенд не делал отдельный запрос за именем клиента
    /// для каждой строки таблицы (проблема N+1 запросов).
    /// </summary>
    public string ClientFullName { get; set; } = string.Empty;

    /// <summary>
    /// Тип абонемента: 'single', 'month', 'year'.
    /// </summary>
    public string Type { get; set; } = string.Empty;

    /// <summary>
    /// Дата начала действия абонемента.
    /// </summary>
    public DateTime StartDate { get; set; }

    /// <summary>
    /// Дата окончания действия абонемента.
    /// Рассчитывается автоматически при создании на основе типа:
    /// - single: start_date + 30 дней
    /// - month:  start_date + 30 дней
    /// - year:   start_date + 365 дней
    /// </summary>
    public DateTime EndDate { get; set; }

    /// <summary>
    /// Лимит посещений (сколько раз можно посетить зал).
    /// - single: 1
    /// - month/year: 0 (безлимит)
    /// </summary>
    public int TotalVisits { get; set; }

    /// <summary>
    /// Количество использованных посещений.
    /// Увеличивается автоматически при регистрации посещения.
    /// </summary>
    public int UsedVisits { get; set; }

    /// <summary>
    /// Статус абонемента: 'active', 'completed', 'expired', 'cancelled'.
    /// См. описание бизнес-логики статусов выше.
    /// </summary>
    public string Status { get; set; } = string.Empty;
}