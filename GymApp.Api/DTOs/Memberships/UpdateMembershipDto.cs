namespace GymApp.Api.DTOs.Memberships;

/// <summary>
/// DTO для обновления абонемента.
/// Используется в PUT /api/memberships/{id}
/// 
/// ═══════════════════════════════════════════════════════════════
/// БИЗНЕС-ЛОГИКА ОБНОВЛЕНИЯ АБОНЕМЕНТА:
/// ═══════════════════════════════════════════════════════════════
/// 
/// 1. Разрешено менять ТОЛЬКО Status и EndDate.
///    Type, ClientId, StartDate, TotalVisits менять НЕЛЬЗЯ 
///    (это уже куплено и зафиксировано).
/// 
/// 2. Статус 'cancelled' используется ТОЛЬКО для ЧП:
///    - Возврат денег клиенту
///    - Нарушение правил зала
///    - Ошибка при создании абонемента
/// 
/// 3. ПРОДЛЕНИЕ = создание НОВОГО абонемента:
///    - НЕ используйте Update для продления!
///    - Создайте новый абонемент через POST /api/memberships
///    - Старый абонемент автоматически закроется со статусом 'completed'
/// 
/// 4. EndDate меняется только для ручного исправления ошибок
///    (например, админ случайно поставил не ту дату).
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЛИДАЦИЯ (FluentValidation):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ ПРОВЕРЯЕТСЯ в UpdateMembershipDtoValidator:
///    - Status (если передан) ∈ {'active', 'cancelled'}
///    - EndDate (если передана) не в прошлом
/// 
/// ❌ НЕ ПРОВЕРЯЕТСЯ в валидаторе (проверяется в сервисе):
///    - EndDate >= StartDate абонемента
///      → Валидатор не знает StartDate конкретного абонемента
///    - Существование абонемента (ID из URL)
///      → Валидатор не имеет доступа к БД
///    - Статус абонемента (нельзя менять completed/expired)
///      → Это бизнес-логика, требует запроса к БД
/// 
/// ⚠️ ВАЖНО: Оба поля опциональные (nullable).
///    Если поле null, значит, его не нужно обновлять.
/// </summary>
public class UpdateMembershipDto
{
    /// <summary>
    /// Новый статус абонемента.
    /// Можно изменить на 'cancelled' (для ЧП: возвраты, нарушения) 
    /// или 'active' (если нужно откатить из cancelled).
    /// Опциональное поле (nullable).
    /// 
    /// ⚠️ НЕ ИСПОЛЬЗУЕТСЯ для продления!
    ///    Продление = создание НОВОГО абонемента через POST.
    /// 
    /// ⚠️ Статусы 'completed' и 'expired' устанавливаются АВТОМАТИЧЕСКИ:
    ///    - 'completed' — при достижении лимита посещений ИЛИ при автозакрытии старого абонемента
    ///    - 'expired' — при регистрации посещения, если дата прошла
    /// 
    /// Проверка допустимых значений происходит в UpdateMembershipDtoValidator.
    /// </summary>
    public string? Status { get; set; }

    /// <summary>
    /// Новая дата окончания абонемента.
    /// Используется для ручного исправления ошибок 
    /// (например, админ случайно поставил не ту дату).
    /// Опциональное поле (nullable).
    /// 
    /// ⚠️ НЕ ИСПОЛЬЗУЕТСЯ для продления!
    ///    Продление = создание НОВОГО абонемента через POST.
    /// 
    /// ⚠️ Проверка "EndDate >= StartDate абонемента" происходит в сервисе,
    ///    потому что валидатор не знает StartDate конкретного абонемента.
    /// </summary>
    public DateTime? EndDate { get; set; }
}