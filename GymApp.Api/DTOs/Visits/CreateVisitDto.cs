namespace GymApp.Api.DTOs.Visits;

/// <summary>
/// DTO для регистрации посещения.
/// Используется в POST /api/visits
/// 
/// ═══════════════════════════════════════════════════════════════
/// БИЗНЕС-ЛОГИКА РЕГИСТРАЦИИ ПОСЕЩЕНИЯ:
/// ═══════════════════════════════════════════════════════════════
/// 
/// 1. Клиент передаёт только MembershipId (ID абонемента).
///    Опционально: TrainerId (ID тренера) и ProcessedByUserId (ID оператора).
/// 
/// 2. VisitTime (время посещения) устанавливается АВТОМАТИЧЕСКИ в сервисе
///    как DateTime.Now (текущее время).
/// 
/// 3. Сервис проверяет:
///    - Абонемент существует?
///    - Статус абонемента = 'active'? (проверяется после автообновления статуса)
///    - Не истёк ли абонемент по дате? (через CheckAndUpdateStatusAsync)
///    - Не исчерпан ли лимит посещений? (для single)
/// 
/// 4. Если всё ок:
///    - Создаётся запись в visits
///    - used_visits увеличивается на 1
///    - Если used_visits == total_visits → статус абонемента = 'completed'
/// 
/// ═══════════════════════════════════════════════════════════════
/// ВАЛИДАЦИЯ (FluentValidation):
/// ═══════════════════════════════════════════════════════════════
/// 
/// ✅ ПРОВЕРЯЕТСЯ в CreateVisitDtoValidator:
///    - MembershipId > 0
///    - TrainerId (если передан) > 0
///    - ProcessedByUserId (если передан) > 0
/// 
/// ❌ НЕ ПРОВЕРЯЕТСЯ в валидаторе (проверяется в сервисе):
///    - Существование абонемента (MembershipId ссылается на реальный абонемент)
///      → Валидатор не имеет доступа к БД
///    - Статус абонемента (должен быть 'active')
///      → Это бизнес-логика, требует запроса к БД
///    - Лимит посещений (used_visits < total_visits)
///      → Это бизнес-логика, требует запроса к БД
/// </summary>
public class CreateVisitDto
{
    /// <summary>
    /// ID абонемента, по которому регистрируется посещение.
    /// Обязательное поле, должно ссылаться на существующий абонемент.
    /// 
    /// Проверка существования абонемента и его статуса происходит в VisitService,
    /// а не в валидаторе, потому что валидатор не имеет доступа к БД.
    /// </summary>
    public int MembershipId { get; set; }

    /// <summary>
    /// ID тренера, который провёл тренировку (опционально).
    /// Если null → клиент занимался самостоятельно.
    /// </summary>
    public int? TrainerId { get; set; }

    /// <summary>
    /// ID оператора (system_user), который зарегистрировал посещение (опционально).
    /// Если null → посещение зарегистрировано через терминал самообслуживания.
    /// </summary>
    public int? ProcessedByUserId { get; set; }
}